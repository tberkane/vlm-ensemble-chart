def plot_early_stopping_comparison():
    """Create side-by-side plot comparing F1 scores and total samples with and without early stopping."""
    plt.style.use("default")

    # Ensemble sizes from 1 to 20
    ensemble_sizes = list(range(1, 21))

    # Calculate total samples for no early stop: 1000 * ensemble_size
    no_early_stop_samples = [1000 * size for size in ensemble_sizes]

    # Colors for different hyperparameter combinations
    colors = ["#648fff", "#785ef0", "#dc267f", "#fe6100", "#ffb000"]

    # Create side-by-side subplots
    fig, (ax1, ax2) = plt.subplots(
        1, 2, figsize=(FIG_W * 2, FIG_H), constrained_layout=True
    )

    color_no_early_stop = "#999999"

    # Plot early stop curves for each hyperparameter combination
    for idx, (hyperparam_label, data) in enumerate(early_stop_data.items()):
        f1_scores = data["f1"]
        convergence = data["convergence"]

        # Calculate total samples for early stop: cumulative sum of 1000 * convergence (percentage)
        early_stop_samples = []
        cumulative_sum = 0
        for conv_pct in convergence:
            cumulative_sum += 1000 * (1.0 - conv_pct / 100.0)
            early_stop_samples.append(cumulative_sum)

        color = colors[idx % len(colors)]

        # Left plot: F1 scores
        ax1.plot(
            ensemble_sizes,
            f1_scores,
            color=color,
            linestyle="-",
            linewidth=1.2,
            label=f"Early Stop ({hyperparam_label})",
            alpha=0.7,
        )

        # Right plot: Total samples
        ax2.plot(
            ensemble_sizes,
            early_stop_samples,
            color=color,
            linestyle="-",
            linewidth=1.2,
            label=f"Early Stop ({hyperparam_label})",
            alpha=0.7,
        )

    # Plot no early stop curve
    ax1.plot(
        ensemble_sizes,
        no_early_stop_f1,
        color=color_no_early_stop,
        linestyle="--",
        linewidth=1.2,
        label="No Early Stop",
        alpha=0.7,
    )

    ax2.plot(
        ensemble_sizes,
        no_early_stop_samples,
        color=color_no_early_stop,
        linestyle="--",
        linewidth=1.2,
        label="No Early Stop",
        alpha=0.7,
    )

    # Configure left plot
    ax1.set_xlabel("Ensemble Size")
    ax1.set_ylabel("F1")
    ax1.grid(True, alpha=0.25, linestyle="--", linewidth=0.5)
    ax1.set_axisbelow(True)
    ax1.set_xlim(0.5, 20.5)
    ax1.set_xticks(range(1, 21, 2))
    ax1.spines["top"].set_visible(False)
    ax1.spines["right"].set_visible(False)
    ax1.spines["left"].set_linewidth(0.6)
    ax1.spines["bottom"].set_linewidth(0.6)
    ax1.legend(
        loc="best",
        frameon=True,
        fancybox=False,
        framealpha=0.95,
        borderpad=0.3,
        handlelength=2.0,
        handletextpad=0.6,
        labelspacing=0.3,
        fontsize=6,
    )

    # Configure right plot
    ax2.set_xlabel("Ensemble Size")
    ax2.set_ylabel("Total Number of Samples")
    ax2.grid(True, alpha=0.25, linestyle="--", linewidth=0.5)
    ax2.set_axisbelow(True)
    ax2.set_xlim(0.5, 20.5)
    ax2.set_xticks(range(1, 21, 2))
    ax2.spines["top"].set_visible(False)
    ax2.spines["right"].set_visible(False)
    ax2.spines["left"].set_linewidth(0.6)
    ax2.spines["bottom"].set_linewidth(0.6)
    ax2.legend(
        loc="best",
        frameon=True,
        fancybox=False,
        framealpha=0.95,
        borderpad=0.3,
        handlelength=2.0,
        handletextpad=0.6,
        labelspacing=0.3,
        fontsize=6,
    )

    # Save plot
    output_dir = Path(__file__).parent.parent / "outputs" / "early_stopping"
    output_dir.mkdir(parents=True, exist_ok=True)

    output_plot = output_dir / "early_stopping_comparison.png"
    fig.savefig(output_plot, dpi=600, facecolor="white", bbox_inches="tight")
    pdf_path = output_plot.with_suffix(".pdf")
    fig.savefig(pdf_path, dpi=600, facecolor="white", bbox_inches="tight")
    print(f"Saved plot to {output_plot}")
    print(f"Saved plot to {pdf_path}")


if __name__ == "__main__":
    plot_early_stopping_comparison()
